n_ord = n_err = n_rename = 0
for room in d['rooms']:
    for pt in room['points']:
        t = pt['t']
        # compound-verbs 房里的重复「かねる」→ 换成不同的复合动词
        if room['id'] == 'compound-verbs' and t == '～かねる（难以…）':
            pt.update({
                't': '～おとす（丢失/落下）',
                'core': '动词ます形去ます+おとす，表「丢掉/落下」。他动词，对象用 を。',
                'formula': '动词ます形去ます＋おとす',
                'ex': [{'en': '私は駅前で鍵を落としました。', 'zh': '我在车站前把钥匙弄丢了。'},
                       {'en': '私の鍵を誰かが落としました。', 'zh': '有人把我的钥匙弄丢了。'}],
                'trap': '落とす=他动词（弄丢），落ちる=自动词（掉了）——「我丢了钥匙」用落とす。',
                'ord': ['私の', '鍵を', '誰かが', '落としました'],
                'err': {'wrong': '鍵が落としました', 'fixes': '鍵を落としました'}})
            n_rename += 1
            t = pt['t']
        f = fix.get(t)
        if not f:
            continue
        if not pt.get('ord') or len(pt.get('ord') or []) != 4:
            pt['ord'] = f['ord']; n_ord += 1
        e = pt.get('err')
        if not e or not e.get('wrong') or e.get('wrong') == e.get('fixes'):
            pt['err'] = f['err']; n_err += 1
        # 修例句英文笔误
        for ex in pt.get('ex', []):
            if 'quality' in ex.get('en', ''):
                ex['en'] = '安くても、品質が悪いのに、買わないほうがいい。'

